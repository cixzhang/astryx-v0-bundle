#!/usr/bin/env node
import {createHash} from 'node:crypto';
import {readFile, writeFile, mkdir, rm, readdir} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const catalogPath = path.join(root, 'catalog/astryx-0.6.3.json');
const catalog = JSON.parse(await readFile(catalogPath, 'utf8'));

const cliEntry = fileURLToPath(import.meta.resolve('@astryxdesign/cli'));
const cliRoot = path.resolve(path.dirname(cliEntry), '../../..');
const cliPackage = JSON.parse(
  await readFile(path.join(cliRoot, 'package.json'), 'utf8'),
);
if (cliPackage.version !== catalog.source.packageVersion) {
  throw new Error(
    `Catalog expects @astryxdesign/cli ${catalog.source.packageVersion}, installed ${cliPackage.version}`,
  );
}

const {stripTemplateAssetRefs} = await import(
  pathToFileURL(path.join(cliRoot, 'api/template/template.mjs'))
);

const generatedRoots = [
  'examples/templates',
  'examples/blocks',
  'examples/components',
  'verification/src/generated',
];
if (!check) {
  await Promise.all(
    generatedRoots.map((directory) =>
      rm(path.join(root, directory), {recursive: true, force: true}),
    ),
  );
}

const publicUrlRewrites = new Map([
  ['https://example.com/people/itai-jordaan', 'https://example.com/'],
  ['https://example.com/hooks', 'https://example.com/'],
  [
    'https://developer.mozilla.org/favicon-48x48.cbbd161b.png',
    'https://developer.mozilla.org/favicon-48x48.png',
  ],
  ['https://sarahchen.dev', 'https://example.com'],
]);
const adaptForV0 = (source) => {
  let adapted = stripTemplateAssetRefs(source);
  for (const [from, to] of publicUrlRewrites) adapted = adapted.replaceAll(from, to);
  return adapted;
};

const outputs = new Map();
for (const entry of catalog.templates) {
  const prefix = 'packages/cli/';
  if (!entry.sourcePath.startsWith(prefix)) {
    throw new Error(`Unexpected source path for ${entry.id}: ${entry.sourcePath}`);
  }
  const source = await readFile(
    path.join(cliRoot, entry.sourcePath.slice(prefix.length)),
    'utf8',
  );
  outputs.set(entry.targetPath, adaptForV0(source));
}

const curated = {
  actions: 'components/Button/ButtonShowcase',
  forms: 'components/FormLayout/FormLayoutShowcase',
  layout: 'components/Layout/LayoutShowcase',
  data: 'components/Table/TableShowcase',
  overlays: 'components/Dialog/DialogShowcase',
  navigation: 'components/AppShell/AppShellShowcase',
  feedback: 'components/Banner/BannerShowcase',
  content: 'components/Markdown/MarkdownShowcase',
};
for (const [name, source] of Object.entries(curated)) {
  outputs.set(
    `examples/components/${name}.tsx`,
    `export {default} from '../blocks/${source}';\n`,
  );
}

const examplesManifest = {
  schemaVersion: 1,
  source: catalog.source,
  counts: catalog.scope,
  entries: catalog.templates.map((entry) => ({
    id: entry.id,
    kind: entry.kind,
    name: entry.name,
    description: entry.description,
    status: entry.upstreamStatus,
    path: entry.targetPath,
    dependencies: entry.dependencies,
    components: entry.components,
  })),
};
outputs.set('examples/manifest.json', `${JSON.stringify(examplesManifest, null, 2)}\n`);

const allEntryMetadata = [
  ...catalog.templates.map((entry) => ({
    id: entry.id,
    kind: entry.kind,
    name: entry.name,
    status: entry.upstreamStatus,
    path: entry.targetPath,
  })),
  ...Object.keys(curated).map((name) => ({
    id: `component:${name}`,
    kind: 'component-example',
    name,
    status: 'ready',
    path: `examples/components/${name}.tsx`,
  })),
].sort((a, b) => a.id.localeCompare(b.id));

const importLines = allEntryMetadata.map((entry) => {
  const relative = path
    .relative(
      path.join(root, 'verification/src/generated'),
      path.join(root, entry.path),
    )
    .split(path.sep)
    .join('/');
  const specifier = relative.startsWith('.') ? relative : `./${relative}`;
  return `  ${JSON.stringify(entry.id)}: () => import(${JSON.stringify(specifier)}),`;
});
const generatedEntries = `// Generated by scripts/sync-astryx-examples.mjs. Do not edit.\n\nexport const entryMetadata = ${JSON.stringify(allEntryMetadata, null, 2)} as const;\n\nexport const entryLoaders = {\n${importLines.join('\n')}\n} as const;\n\nexport type EntryId = keyof typeof entryLoaders;\n`;
outputs.set('verification/src/generated/entries.ts', generatedEntries);

const pages = catalog.templates.filter((entry) => entry.kind === 'page-template');
const blocks = catalog.templates.filter((entry) => entry.kind === 'block-template');
const blockGroups = new Map();
for (const entry of blocks) {
  const parts = entry.targetPath.split('/');
  const group = parts[2] === 'components' ? parts[3] : parts[2];
  blockGroups.set(group, (blockGroups.get(group) ?? 0) + 1);
}
const pageRows = pages
  .map(
    (entry) =>
      `| \`${entry.id.slice(5)}\` | ${entry.name.replaceAll('|', '\\|')} | ${entry.upstreamStatus} | \`${entry.targetPath}\` |`,
  )
  .join('\n');
const blockRows = [...blockGroups.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([name, count]) => `| \`${name}\` | ${count} |`)
  .join('\n');
outputs.set(
  'references/template-index.md',
  `# Generated template index\n\nSource: Astryx ${catalog.source.packageVersion} at \`${catalog.source.gitCommit}\`. Regenerate with \`pnpm generate\`; do not edit by hand.\n\n## Page templates (${pages.length})\n\n| Slug | Name | Status | Source in this bundle |\n|---|---|---|---|\n${pageRows}\n\n## Block templates (${blocks.length})\n\n| Component or group | Count |\n|---|---:|\n${blockRows}\n\nFor exact block names, requirements, paths, dependencies, and component usage, read \`examples/manifest.json\` or \`catalog/astryx-0.6.3.json\`.\n`,
);

const hashes = [...outputs.entries()]
  .filter(
    ([file]) =>
      file.startsWith('examples/templates/') || file.startsWith('examples/blocks/'),
  )
  .map(([file, content]) => ({
    id: catalog.templates.find((entry) => entry.targetPath === file)?.id,
    path: file,
    sha256: createHash('sha256').update(content).digest('hex'),
  }))
  .sort((a, b) => a.path.localeCompare(b.path));
const [v0Json, skill] = await Promise.all([
  readFile(path.join(root, 'v0.json'), 'utf8'),
  readFile(path.join(root, 'SKILL.md'), 'utf8'),
]);
const packageJson = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'));
const bundleManifest = {
  schemaVersion: 1,
  bundleVersion: packageJson.version,
  v0SchemaVersion: catalog.source.v0SchemaVersion,
  astryx: {
    version: catalog.source.packageVersion,
    ref: catalog.source.gitTag,
    commit: catalog.source.gitCommit,
  },
  counts: catalog.scope,
  contractHashes: {
    v0Json: createHash('sha256').update(v0Json).digest('hex'),
    skill: createHash('sha256').update(skill).digest('hex'),
    catalog: createHash('sha256')
      .update(await readFile(catalogPath))
      .digest('hex'),
  },
  entries: hashes,
};
outputs.set('bundle.manifest.json', `${JSON.stringify(bundleManifest, null, 2)}\n`);

const failures = [];
for (const [relativePath, content] of [...outputs.entries()].sort(([a], [b]) =>
  a.localeCompare(b),
)) {
  const absolutePath = path.join(root, relativePath);
  if (check) {
    try {
      const existing = await readFile(absolutePath, 'utf8');
      if (existing !== content) failures.push(`stale: ${relativePath}`);
    } catch {
      failures.push(`missing: ${relativePath}`);
    }
  } else {
    await mkdir(path.dirname(absolutePath), {recursive: true});
    await writeFile(absolutePath, content);
  }
}

async function listFiles(directory) {
  const absolute = path.join(root, directory);
  let entries;
  try {
    entries = await readdir(absolute, {withFileTypes: true});
  } catch {
    return [];
  }
  const files = [];
  for (const entry of entries) {
    const relative = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...(await listFiles(relative)));
    else files.push(relative.split(path.sep).join('/'));
  }
  return files;
}

if (check) {
  const expected = new Set(outputs.keys());
  for (const directory of generatedRoots) {
    for (const file of await listFiles(directory)) {
      if (!expected.has(file)) failures.push(`unexpected: ${file}`);
    }
  }
  if (failures.length) {
    throw new Error(
      `Generated files are out of date:\n${failures.slice(0, 40).join('\n')}${failures.length > 40 ? `\n...and ${failures.length - 40} more` : ''}`,
    );
  }
  console.log(`Verified ${outputs.size} generated files.`);
} else {
  console.log(
    `Generated ${outputs.size} files from @astryxdesign/cli ${cliPackage.version}.`,
  );
}
